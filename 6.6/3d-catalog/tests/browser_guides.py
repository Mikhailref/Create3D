    plain=T/'guides-plain.html';plain.write_text(h0.replace(re.search(r'id="__CAD_ANNOTATIONS_DATA__"[^>]*>(.*?)</script>',h0,re.S).group(1),json.dumps(d0,ensure_ascii=False)))
